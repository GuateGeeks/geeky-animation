"""Copy the public static site into _site using Python's standard library.

Run from any directory. The allowlist excludes Git metadata, workflows, tests,
export caches, local credentials and development tooling from the Pages upload.
Existing animation assets are copied, never regenerated by this build.
"""
from pathlib import Path
import shutil

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / '_site'
ENTRIES = ('index.html', 'site.css', 'site.js', 'manifest.json', 'assets', 'demo',
           'dist', 'docs', 'examples', 'src', 'previews', 'live', 'vendor')
EXTENSIONS = {'.html', '.css', '.js', '.mjs', '.json', '.md', '.png', '.svg',
              '.webp', '.gif', '.jpg', '.mp4', '.pdf', '.docx'}


def build():
    files = []
    for entry in ENTRIES:
        source = ROOT / entry
        if source.is_symlink():
            raise RuntimeError(f'Symlinks are not allowed in site inputs: {entry}')
        if not source.exists():
            raise RuntimeError(f'Missing public site input: {entry}')
        candidates = [source] if source.is_file() else source.rglob('*')
        for item in candidates:
            relative = item.relative_to(ROOT)
            if item.is_symlink():
                raise RuntimeError(f'Symlinks are not allowed in the site: {relative}')
            if item.is_dir():
                continue
            if any(part.startswith('.') or part == '__pycache__' for part in relative.parts):
                raise RuntimeError(f'Unexpected hidden or cache file: {relative}')
            if item.suffix.lower() not in EXTENSIONS:
                raise RuntimeError(f'Unapproved static file extension: {relative}')
            files.append((item, relative))
    if OUTPUT.is_symlink():
        raise RuntimeError('Refusing to replace a symlink at _site')
    if OUTPUT.exists():
        shutil.rmtree(OUTPUT)
    OUTPUT.mkdir()
    for source, relative in files:
        destination = OUTPUT / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(source, destination)
    total = sum(source.stat().st_size for source, _ in files)
    print(f'Built {len(files)} public files in _site ({total:,} bytes).')


if __name__ == '__main__':
    build()
